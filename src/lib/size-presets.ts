const norm = (s: string) => s.replace(/\s|·|\(|\)/g, "").toLowerCase();

export interface ResolvedRoom {
  room: string;
  /** item_id → 수량 */
  items: Record<string, number>;
}

export interface ResolvedPreset {
  rooms: ResolvedRoom[];
  /** 실제 품목 목록에 없어서 담지 못한 품목 (품목 등록 필요) */
  missing: { room: string; name: string; qty: number }[];
}

/**
 * 기본품목 이름을 실제 품목 id 로 바꿉니다.
 * 같은 이름이 이미 있으면 그 품목 id(=3D 그림)를 그대로 씁니다.
 */
export function resolvePreset(
  rooms: PresetRoom[],
  catalog: { id: string; name: string }[],
): ResolvedPreset {
  const byName = new Map<string, string>();
  for (const c of catalog) if (!byName.has(norm(c.name))) byName.set(norm(c.name), c.id);

  const out: ResolvedRoom[] = [];
  const missing: ResolvedPreset["missing"] = [];
  for (const pr of rooms) {
    const items: Record<string, number> = {};
    for (const it of pr.items) {
      const target = NAME_ALIAS[it.name] ?? it.name;
      const id = byName.get(norm(target)) ?? byName.get(norm(it.name));
      if (!id) {
        missing.push({ room: pr.room, name: it.name, qty: it.qty });
        continue;
      }
      items[id] = (items[id] ?? 0) + Math.max(1, it.qty);
    }
    out.push({ room: pr.room, items });
  }
  return { rooms: out, missing };
}

/** 평수별 기본품목에 등장하는 공간 이름 */
export function presetRoomNames(rooms: PresetRoom[]): string[] {
  return rooms.map((r2) => r2.room);
}
