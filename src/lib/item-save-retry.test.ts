import { it } from "node:test";
import { strict as assert } from "node:assert";
import { retryItemStorage } from "./item-save-retry";
it("upload transient failure retries same generated bytes after backoff", async () => {
  let attempts=0; const waits:number[]=[];
  const r=await retryItemStorage(async()=>({error:++attempts<3?{statusCode:503}:null}),async ms=>{waits.push(ms);});
  assert.equal(attempts,3); assert.deepEqual(waits,[800,1600]); assert.equal(r.error,null);
});
it("upload permission error is terminal and does not retry", async () => {
  let attempts=0;
  await retryItemStorage(async()=>{attempts++;return {error:{statusCode:403}};},async()=>{throw new Error("must not retry");});
  assert.equal(attempts,1);
});